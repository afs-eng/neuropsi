def lookup_subscale(group: str, code: str, score: int) -> dict:
    mean, sd, cuts = SUBSCALE_NORMS[group][code]
    band_index = next(index for first, index in reversed(cuts) if score >= first)
    return {
        "mean": mean,
        "sd": sd,
        "manual_percentile_band": BANDS[band_index],
        "manual_classification": "Inferior" if band_index < 3 else "Média" if band_index < 5 else "Superior",
    }


def lookup_total(group: str, score: int) -> dict:
    t_score = TOTAL_T_SCORES[group][score]
    if isinstance(t_score, str):
        classification = "Muito Baixo" if t_score.startswith("<") else "Muito Alto"
    else:
        classification = next(label for upper, label in [
            (29, "Muito Baixo"), (39, "Baixo"), (49, "Média Inferior"),
            (50, "Média"), (60, "Média Superior"), (70, "Alto"), (float("inf"), "Muito Alto"),
        ] if t_score <= upper)
    return {"t_score": t_score, "manual_classification": classification}
