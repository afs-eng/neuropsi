def percentile_for_score(informant: str, gender: str, domain: str, scale: str, score: float) -> int | None:
    values = NORMS.get((informant, gender, domain), {}).get(scale)
    if not values:
        return None
    for percentile, cutoff in zip(PERCENTILES, values):
        if score >= cutoff:
            return percentile
    return 1


def percentile_range_for_score(informant: str, gender: str, domain: str, scale: str, score: float) -> tuple[int, int] | None:
    values = NORMS.get((informant, gender, domain), {}).get(scale)
    if not values:
        return None
    for index, cutoff in enumerate(values):
        if score >= cutoff:
            tied_percentiles = [PERCENTILES[index]]
            for next_percentile, next_cutoff in zip(PERCENTILES[index + 1 :], values[index + 1 :]):
                if next_cutoff != cutoff:
                    break
                tied_percentiles.append(next_percentile)
            return min(tied_percentiles), max(tied_percentiles)
    return 1, 1


def format_percentile_range(percentile_range: tuple[int, int] | None) -> str | None:
    if percentile_range is None:
        return None
    lower, upper = percentile_range
    if lower == upper:
        return str(upper)
    return f"P{lower}-P{upper}"
